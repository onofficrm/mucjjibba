export function linesFor(cue: NarrationCue, style: VoiceStyle): string[] {
  if (style === 'minimal') {
    return NARRATION_STYLE_EXTRA.minimal[cue] ?? NARRATION_COMMON[cue] ?? [];
  }
  const extra = NARRATION_STYLE_EXTRA[style][cue] ?? [];
  return [...(NARRATION_COMMON[cue] ?? []), ...extra];
}
